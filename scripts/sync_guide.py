"""Generate ``src/tackboard/guide.py`` from the two documents that own the text.

The guide is tiered: a short core that every agent loads, and reference topics
read on demand. Both already have a home — the core is the "Agent quickstart"
block in ``README.md`` (which must stay byte-identical to ``tack guide``), and
each topic is a section of ``SKILL.md``. This script reads those two files and
writes the Python constant module, so the shipped CLI and the documents cannot
drift apart.

Usage::

    uv run python scripts/sync_guide.py           # rewrite src/tackboard/guide.py
    uv run python scripts/sync_guide.py --check   # exit 1 when it is stale

Editing guide.py by hand is pointless: the next run overwrites it.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
README_PATH = REPO_ROOT / "README.md"
SKILL_PATH = REPO_ROOT / "SKILL.md"
TARGET_PATH = REPO_ROOT / "src" / "tackboard" / "guide.py"

QUICKSTART_HEADING = "## Agent quickstart"
FENCE_OPEN = "```text"
FENCE_CLOSE = "```"

#: topic name -> the SKILL.md section headings that make up its text, in
#: reading order. Every heading must exist; a multi-heading topic is printed as
#: its sections joined by one blank line.
TOPIC_SECTIONS: dict[str, tuple[str, ...]] = {
    "commands": ("## Command reference",),
    "documents": (
        "## Field limits",
        "## The JSON contract",
        "## Document shapes",
        "## The `counts` object",
    ),
    "plans": ("## Plans",),
    "refs": ("## Typed note refs",),
    "reject": ("## Rejections and reviewer separation",),
    "memo": ("## The project memo",),
    "force": ("## Forcing a transition (`--force`)",),
    "doctor": ("## The `doctor` document",),
    "web": ("## Web view",),
    "schemas": ("## JSON Schemas",),
    "practices": ("## Best practices",),
    "pitfalls": ("## Pitfalls (things that look broken but are not)",),
    "verification": ("## Verification",),
}

#: the order ``tack guide --topics`` prints.
TOPIC_ORDER: tuple[str, ...] = tuple(TOPIC_SECTIONS)

HEADER = '''\
"""The tiered guide text: one always-loaded core, and reference topics.

Generated by ``scripts/sync_guide.py`` from ``README.md`` (the core: its "Agent
quickstart" block) and ``SKILL.md`` (one section per topic). Edit those files,
re-run the script, and keep the freshness test green — a hand edit here is lost
on the next run.
"""

from __future__ import annotations

'''


def _sections(text: str) -> dict[str, str]:
    """Map each level-two heading (with its ``## ``) to the body below it."""
    lines = text.splitlines()
    found: dict[str, list[str]] = {}
    current: str | None = None
    for line in lines:
        if line.startswith("## "):
            current = line.rstrip()
            found[current] = []
        elif current is not None:
            found[current].append(line.rstrip())
    return {heading: "\n".join(body).strip("\n") for heading, body in found.items()}


def _core_text(readme: str) -> str:
    """The fenced block under "## Agent quickstart" — the text `tack guide` prints."""
    lines = readme.splitlines()
    try:
        start = lines.index(QUICKSTART_HEADING)
    except ValueError as exc:  # pragma: no cover - the document always has it
        raise SystemExit(f"README.md has no {QUICKSTART_HEADING!r} section") from exc
    opened = lines.index(FENCE_OPEN, start)
    closed = lines.index(FENCE_CLOSE, opened + 1)
    return "\n".join(lines[opened + 1 : closed]) + "\n"


def topic_title(heading: str) -> str:
    """The human title of a section heading, without the markdown marker."""
    return heading.removeprefix("## ").strip()


def build_text(readme: str | None = None, skill: str | None = None) -> str:
    """Render the whole ``guide.py`` module as text."""
    readme = README_PATH.read_text(encoding="utf-8") if readme is None else readme
    skill = SKILL_PATH.read_text(encoding="utf-8") if skill is None else skill

    sections = _sections(skill)
    missing = [
        heading
        for headings in TOPIC_SECTIONS.values()
        for heading in headings
        if heading not in sections
    ]
    if missing:
        raise SystemExit(f"SKILL.md is missing topic sections: {sorted(set(missing))}")

    parts: list[str] = [HEADER]
    parts.append('CORE_GUIDE = r"""' + _core_text(readme).rstrip("\n") + '"""')
    parts.append("")
    parts.append("TOPICS: dict[str, str] = {")
    for name, headings in TOPIC_SECTIONS.items():
        body = "\n\n".join(sections[heading] for heading in headings)
        if "'''" in body:
            raise SystemExit(f"topic {name!r} contains a triple single quote")
        parts.append(f"    {name!r}: r'''" + body.rstrip("\n") + "''',")
    parts.append("}")
    parts.append("")
    parts.append("TOPIC_TITLES: dict[str, str] = {")
    for name, headings in TOPIC_SECTIONS.items():
        parts.append(f"    {name!r}: {topic_title(headings[0])!r},")
    parts.append("}")
    parts.append("")
    parts.append("TOPIC_ORDER: tuple[str, ...] = (")
    for name in TOPIC_ORDER:
        parts.append(f"    {name!r},")
    parts.append(")")
    parts.append("")
    parts.append('__all__ = ["CORE_GUIDE", "TOPIC_ORDER", "TOPIC_TITLES", "TOPICS"]')
    parts.append("")
    return "\n".join(parts)


def main(argv: list[str]) -> int:
    text = build_text()
    check = "--check" in argv
    current = TARGET_PATH.read_text(encoding="utf-8") if TARGET_PATH.exists() else ""
    if check:
        if current != text:
            print(
                f"stale: {TARGET_PATH.relative_to(REPO_ROOT)} does not match "
                "README.md and SKILL.md; run scripts/sync_guide.py",
                file=sys.stderr,
            )
            return 1
        print(f"current: {TARGET_PATH.relative_to(REPO_ROOT)} matches the documents")
        return 0
    TARGET_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
